// All S3 access of the app (ADR-0004, ADR-0005). No other module may import the
// S3 client: handlers call these functions.
//
// The `data` bucket has two prefixes (docs/architecture.md → "S3 buckets"):
// - `uploads/{id}.pdf`: the PDF, uploaded by the browser with a presigned POST and
//   deleted by a lifecycle rule after 30 days (NFR-SEC-06).
// - `results/{id}.json`: the findings of a completed job (ADR-0004).

import {
  GetObjectCommand,
  HeadObjectCommand,
  NotFound,
  PutObjectCommand,
  S3Client,
} from '@aws-sdk/client-s3';
import { createPresignedPost } from '@aws-sdk/s3-presigned-post';
import { getSignedUrl } from '@aws-sdk/s3-request-presigner';

import { MAX_FILE_SIZE_BYTES } from '@gaceta/shared';
import type { CreateJobResponse, JobResults } from '@gaceta/shared';

import { getDataBucketName } from './config';

/** Presigned URLs (upload and read) expire after 15 minutes (NFR-SEC-04). */
export const PRESIGNED_URL_EXPIRATION_SECONDS = 15 * 60;

/** The only content type the upload accepts (NFR-SEC-08). */
export const PDF_CONTENT_TYPE = 'application/pdf';

const UPLOADS_PREFIX = 'uploads/';
const RESULTS_PREFIX = 'results/';

// Ids are generated by `crypto.randomUUID()` in create-job, so a valid upload key
// is "uploads/" + a UUID + ".pdf". Anything else was not created by this app.
const UPLOAD_KEY_PATTERN =
  /^uploads\/([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})\.pdf$/i;

/** What the browser needs to upload the PDF (same shape as the API response). */
export type UploadPost = CreateJobResponse['upload'];

// Created once per Lambda container and reused by every invocation.
// Tests replace it with aws-sdk-client-mock, which intercepts every S3Client.
const s3Client = new S3Client({});

/** S3 key of a job's PDF: `uploads/{id}.pdf`. */
export function uploadKey(id: string): string {
  return `${UPLOADS_PREFIX}${id}.pdf`;
}

/** S3 key of a job's results: `results/{id}.json`. */
export function resultsKey(id: string): string {
  return `${RESULTS_PREFIX}${id}.json`;
}

/**
 * Returns the job id of an upload key, or `null` if the key is not one of ours.
 *
 * Keys in S3 event notifications are URL-encoded, with spaces written as "+"
 * (for example "uploads%2F3f6c….pdf"), so the key is decoded first.
 */
export function jobIdFromUploadKey(key: string): string | null {
  const decodedKey = decodeS3EventKey(key);
  if (decodedKey === null) {
    return null;
  }

  const match = UPLOAD_KEY_PATTERN.exec(decodedKey);
  if (match === null) {
    return null;
  }
  return match[1] ?? null;
}

function decodeS3EventKey(key: string): string | null {
  // "+" means a space in S3 event keys, but `decodeURIComponent` leaves it as is,
  // so it is replaced first.
  const withSpaces = key.replaceAll('+', ' ');
  try {
    return decodeURIComponent(withSpaces);
  } catch {
    // A malformed escape like "%E0%A4%A" cannot be one of our keys.
    return null;
  }
}

/**
 * Creates the presigned POST the browser uses to upload the PDF straight to S3
 * (ADR-0005). S3 itself rejects the upload unless it is exactly this key, a PDF
 * content type and at most 100 MB (NFR-SEC-08), within 15 minutes (NFR-SEC-04).
 */
export async function createUploadPost(id: string): Promise<UploadPost> {
  const post = await createPresignedPost(s3Client, {
    Bucket: getDataBucketName(),
    Key: uploadKey(id),
    Conditions: [
      ['eq', '$Content-Type', PDF_CONTENT_TYPE],
      ['content-length-range', 1, MAX_FILE_SIZE_BYTES],
    ],
    // The browser sends every field back unchanged, so the Content-Type field
    // matches the condition above.
    Fields: { 'Content-Type': PDF_CONTENT_TYPE },
    Expires: PRESIGNED_URL_EXPIRATION_SECONDS,
  });

  return { url: post.url, fields: post.fields };
}

/** Downloads the PDF of a job. */
export async function getPdfBytes(key: string): Promise<Uint8Array> {
  const output = await s3Client.send(
    new GetObjectCommand({ Bucket: getDataBucketName(), Key: key }),
  );

  if (output.Body === undefined) {
    throw new Error(`S3 object has no body: ${key}`);
  }
  return output.Body.transformToByteArray();
}

/**
 * Returns a presigned read URL of the PDF (valid 15 minutes), or `null` if the
 * PDF no longer exists because the 30-day lifecycle rule deleted it (FR-06).
 */
export async function createPdfReadUrl(key: string): Promise<string | null> {
  const bucket = getDataBucketName();

  // A presigned URL is just a signature: S3 does not check that the object
  // exists when it is created. HeadObject checks it first, so the web app can
  // say "El PDF ya no está disponible" instead of showing a broken viewer.
  try {
    await s3Client.send(new HeadObjectCommand({ Bucket: bucket, Key: key }));
  } catch (err) {
    // S3 only answers "not found" (instead of "access denied") when the role
    // has `s3:ListBucket` on the bucket, which get-job's role has (#30).
    if (err instanceof NotFound) {
      return null;
    }
    throw err;
  }

  return getSignedUrl(
    s3Client,
    new GetObjectCommand({ Bucket: bucket, Key: key }),
    { expiresIn: PRESIGNED_URL_EXPIRATION_SECONDS },
  );
}

/** Stores the findings of a job in `results/{id}.json` (ADR-0004). */
export async function putResults(
  id: string,
  results: JobResults,
): Promise<void> {
  await s3Client.send(
    new PutObjectCommand({
      Bucket: getDataBucketName(),
      Key: resultsKey(id),
      Body: JSON.stringify(results),
      ContentType: 'application/json',
    }),
  );
}

/** Reads the findings of a completed job. */
export async function getResults(key: string): Promise<JobResults> {
  const output = await s3Client.send(
    new GetObjectCommand({ Bucket: getDataBucketName(), Key: key }),
  );

  if (output.Body === undefined) {
    throw new Error(`S3 object has no body: ${key}`);
  }
  const text = await output.Body.transformToString('utf8');

  // Only `putResults` writes under results/, so the JSON has the JobResults shape.
  return JSON.parse(text) as JobResults;
}
